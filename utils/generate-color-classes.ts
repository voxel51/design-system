import * as fs from "fs";
import {
  ActionColor,
  BackgroundColor,
  bgColorClass,
  BorderColor,
  borderColorClass,
  BrandColor,
  IconColor,
  SemanticColor,
  StatusColor,
  TextColor,
  textColorClass,
} from "../src/types/color";
import { ElementState } from "../src/types/element";

const allColors = [
  ...Object.values(ActionColor),
  ...Object.values(BackgroundColor),
  ...Object.values(BrandColor),
  ...Object.values(IconColor),
  ...Object.values(SemanticColor),
  ...Object.values(StatusColor),
  ...Object.values(TextColor),
];

const allBorderColors = Object.values(BorderColor);
const allStates = Object.values(ElementState).filter(
  (s) => s !== ElementState.None
);

function generateClasses() {
  const classes = new Set<string>();

  // Background colors
  allColors.forEach((color) => {
    // Base state - uses mapped class
    classes.add(`bg-${color}`);
    classes.add(`bg-content-${color}`); // Add content- prefix version too

    // With element states - uses variable syntax
    allStates.forEach((state) => {
      classes.add(bgColorClass(color, state));
    });
  });

  // Text colors
  allColors.forEach((color) => {
    // Base state
    classes.add(`text-${color}`);
    classes.add(`text-content-${color}`);

    // With element states
    allStates.forEach((state) => {
      classes.add(textColorClass(color, state));
    });
  });

  // Border colors
  allBorderColors.forEach((color) => {
    // Base state
    classes.add(`border-content-${color}`);

    // With element states
    allStates.forEach((state) => {
      classes.add(borderColorClass(color, state));
    });
  });

  return Array.from(classes).sort();
}

const classes = generateClasses();

// Generate TypeScript file
const tsContent = `// Auto-generated - DO NOT EDIT MANUALLY
// Generated by: npm run generate:colors
// This file ensures Tailwind scans all possible color class permutations

/**
 * All possible color class combinations including:
 * - Background colors with all element states
 * - Text colors with all element states
 * - Border colors with all element states
 */

// Total classes: ${classes.length}

export const GENERATED_COLOR_CLASSES = [
${classes.map((c) => `  '${c}',`).join("\n")}
] as const;

export default GENERATED_COLOR_CLASSES;
`;

const outFile = "src/styles/color-classes.ts";
fs.writeFileSync(outFile, tsContent);

console.log(`✅ Generated ${classes.length} color class permutations`);
console.log(`📁 Output: ${outFile}`);
