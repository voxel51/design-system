import { writeFileSync } from "fs";
import { ZIndex, Z_INDEX_VALUES } from "../src/types/zIndex";
import { default as tokens } from "../src/theme/tokens";

/**
 * Generate a list of CSS variables from a (maybe) nested object.
 *
 * This method will traverse an object and create a variable of the form
 * `${prefix}-${key}: ${value}`
 * for each leaf node in the object.
 *
 * @param config Configuration object
 * @param prefix Prefix to prepend to the CSS variable
 */
const mapNestedAttributes = (
  config: Record<string, any>,
  prefix?: string
): string[] => {
  const result: string[] = [];

  Object.entries(config).forEach(([key, value]) => {
    if (typeof value === "object") {
      result.push(...mapNestedAttributes(value, `${prefix}-${key}`));
    } else if (typeof value === "string") {
      if (prefix) {
        result.push(`${prefix}-${key}: ${value};`);
      } else {
        result.push(`${key}: ${value};`);
      }
    } else {
      throw new Error(
        `Unsupported value type ${typeof value} for key ${prefix}-${key}`
      );
    }
  });

  return result;
};

const tailwindTheme = `/** AUTO-GENERATED by utils/generate-tailwind-theme.ts **/
@theme static {
  /* Colors */
  ${mapNestedAttributes(tokens.colors.light, "--color").join("\n  ")}
  ${mapNestedAttributes(tokens.colors.common, "--color").join("\n  ")}
  
  /* Spacing */
  --spacing: 0.25rem;
  ${Object.entries(tokens.spacing)
    .map(([key, value]) => `--spacing-${key}: ${value};`)
    .join("\n  ")}

  /* Z-Index */
  ${(Object.entries(Z_INDEX_VALUES) as [ZIndex, number | "auto"][])
    .map(([level, value]) => `--z-${level}: ${value};`)
    .join("\n  ")}

  /* Typography */
  ${Object.entries(tokens.typography.fontFamily)
    .map(
      ([key, value]) =>
        `--font-${key}: ${value.map((v) => (v.includes(" ") ? `"${v}"` : v)).join(", ")};`
    )
    .join("\n  ")}
  ${Object.entries(tokens.typography.fontSize)
    .map(([key, value]) => `--text-${key}: ${value};`)
    .join("\n  ")}
}

/* dark theme */
@custom-variant dark (&:where(.dark, .dark *));

.dark {
  ${mapNestedAttributes(tokens.colors.dark, "--color").join("\n  ")}
}
`;

